import pptxgen from 'pptxgenjs';
import { SlideDeckData, StructuredIntelligence } from '../types';

export function exportToPptx(slideDeck: SlideDeckData, structuredData?: StructuredIntelligence): Promise<void> {
  return new Promise((resolve, reject) => {
    try {
      const pres = new pptxgen();

      // Set presentation properties
      pres.layout = 'LAYOUT_16x9';
      pres.author = 'TransformAI - Content Transformation Platform (SIH26154)';
      pres.company = 'National Technical Research Organisation (NTRO)';
      pres.title = slideDeck.deck_title || 'Intelligence Briefing';

      // Theme Colors
      const BG_DARK = '0B192C';
      const BG_CARD = '1E3E62';
      const ACCENT_CYAN = '00ADB5';
      const ACCENT_AMBER = 'FF6500';
      const TEXT_LIGHT = 'EEEEEE';
      const TEXT_MUTED = '94A3B8';

      // 1. TITLE SLIDE
      const titleSlide = pres.addSlide();
      titleSlide.background = { color: BG_DARK };

      // Top classification badge
      titleSlide.addText(
        (structuredData?.classification || 'CONFIDENTIAL // OFFICIAL USE').toUpperCase(),
        {
          x: 0.8,
          y: 0.6,
          w: 8.4,
          h: 0.4,
          fontSize: 11,
          fontFace: 'Arial',
          bold: true,
          color: ACCENT_AMBER,
          charSpacing: 3,
        }
      );

      // Title
      titleSlide.addText(slideDeck.deck_title || structuredData?.title || 'Intelligence Briefing', {
        x: 0.8,
        y: 1.4,
        w: 11.5,
        h: 2.2,
        fontSize: 32,
        fontFace: 'Arial',
        bold: true,
        color: TEXT_LIGHT,
        valign: 'top',
      });

      // Subtitle / Executive line
      if (structuredData?.executive_brief) {
        titleSlide.addText(
          structuredData.executive_brief.slice(0, 240) + '...',
          {
            x: 0.8,
            y: 3.8,
            w: 11.5,
            h: 1.4,
            fontSize: 14,
            fontFace: 'Calibri',
            color: TEXT_MUTED,
            italic: true,
          }
        );
      }

      // Footer tag
      titleSlide.addText(
        `Generated by TransformAI Engine • ${new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })} • AI Transformation Layer`,
        {
          x: 0.8,
          y: 6.5,
          w: 11.5,
          h: 0.4,
          fontSize: 10,
          fontFace: 'Calibri',
          color: '64748B',
        }
      );

      // 2. ITERATE OVER SLIDES
      slideDeck.slides.forEach((slide) => {
        const pSlide = pres.addSlide();
        pSlide.background = { color: BG_DARK };

        // Slide Header bar
        pSlide.addText(`SLIDE ${slide.slide_number.toString().padStart(2, '0')}`, {
          x: 0.8,
          y: 0.5,
          w: 3.0,
          h: 0.3,
          fontSize: 10,
          fontFace: 'Arial',
          bold: true,
          color: ACCENT_CYAN,
        });

        // Slide Title
        pSlide.addText(slide.title, {
          x: 0.8,
          y: 0.8,
          w: 11.5,
          h: 0.8,
          fontSize: 22,
          fontFace: 'Arial',
          bold: true,
          color: TEXT_LIGHT,
        });

        if (slide.subtitle) {
          pSlide.addText(slide.subtitle, {
            x: 0.8,
            y: 1.6,
            w: 11.5,
            h: 0.4,
            fontSize: 12,
            fontFace: 'Calibri',
            color: ACCENT_AMBER,
          });
        }

        // Card Container Background for Bullets
        const startY = slide.subtitle ? 2.1 : 1.8;
        pSlide.addShape(pres.ShapeType.rect, {
          x: 0.8,
          y: startY,
          w: 11.7,
          h: 4.5,
          fill: { color: BG_CARD },
          line: { color: '334E68', width: 1 },
        });

        // Bullet Points
        const bulletItems = slide.bullets.map((b) => ({
          text: b,
          options: {
            bullet: { code: '25AA', color: ACCENT_CYAN },
            fontSize: 13,
            color: TEXT_LIGHT,
            spaceAfter: 10,
          },
        }));

        pSlide.addText(bulletItems, {
          x: 1.1,
          y: startY + 0.3,
          w: 11.1,
          h: 3.9,
          fontFace: 'Calibri',
          valign: 'top',
        });

        // Speaker notes
        if (slide.speaker_notes) {
          pSlide.addNotes(slide.speaker_notes);
        }
      });

      // 3. ENTITIES & METRICS SLIDE (if available)
      if (structuredData?.entities && structuredData.entities.length > 0) {
        const entSlide = pres.addSlide();
        entSlide.background = { color: BG_DARK };

        entSlide.addText('INTELLIGENCE MATRIX: IDENTIFIED ENTITIES & THREAT ACTORS', {
          x: 0.8,
          y: 0.6,
          w: 11.5,
          h: 0.7,
          fontSize: 20,
          fontFace: 'Arial',
          bold: true,
          color: TEXT_LIGHT,
        });

        const rows: pptxgen.TableRow[] = [
          [
            { text: 'Entity Name', options: { bold: true, fill: { color: BG_CARD }, color: ACCENT_CYAN } },
            { text: 'Classification Type', options: { bold: true, fill: { color: BG_CARD }, color: ACCENT_CYAN } },
            { text: 'Intelligence Context', options: { bold: true, fill: { color: BG_CARD }, color: ACCENT_CYAN } },
          ],
        ];

        structuredData.entities.slice(0, 7).forEach((ent) => {
          rows.push([
            { text: ent.name, options: { bold: true, color: TEXT_LIGHT } },
            { text: ent.type.toUpperCase(), options: { color: ACCENT_AMBER } },
            { text: ent.context || 'Referenced in primary report telemetry', options: { color: TEXT_MUTED } },
          ]);
        });

        entSlide.addTable(rows, {
          x: 0.8,
          y: 1.5,
          w: 11.7,
          colW: [3.5, 2.5, 5.7],
          border: { type: 'solid', pt: 1, color: '334E68' },
          fill: { color: '102A43' },
          fontSize: 11,
          fontFace: 'Calibri',
        });
      }

      // Save presentation
      const safeFilename = `${(slideDeck.deck_title || 'TransformAI_Briefing')
        .replace(/[^a-zA-Z0-9_-]/g, '_')
        .slice(0, 30)}_${Date.now()}.pptx`;

      pres.writeFile({ fileName: safeFilename })
        .then(() => resolve())
        .catch((err) => reject(err));
    } catch (e) {
      reject(e);
    }
  });
}
